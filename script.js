function start(m){
    if(m==='test'&&!state.unlocked)return;
    mode=m;
    if(m==='practice'){
        let missed=shuffle(data.filter(x=>state.missed.includes(x.id))).sort((a,b)=>(state.mistakes[b.id]||0)-(state.mistakes[a.id]||0));
        const missedIds=new Set(missed.map(x=>x.id));
        let unseen=shuffle(data.filter(x=>!state.seen.includes(x.id))),
        seen=shuffle(data.filter(x=>state.seen.includes(x.id)&&!missedIds.has(x.id)));
        let unseenIds=new Set(unseen.map(x=>x.id));
        missed=missed.filter(x=>!unseenIds.has(x.id));
        let chosen=[...unseen,
        ...missed,
        ...seen].slice(0,
        practiceQuestionCount());
        questions=shuffle(chosen)
    }
    else if(m==='review'){
        questions=shuffle(state.missed.map(id=>data.find(x=>x.id===id)).filter(Boolean));
        if(!questions.length)return home()
    }
    else questions=shuffle(data).slice(0,
    challengeQuestionCount());
    at=0;
    score=0;
    answers=[];
    show('quiz');
    render()
}
function speak(){
    if(!window.speechSynthesis){
        $('toast').innerHTML=bi('当前浏览器不支持发音，请启用音频或更换浏览器。','Audio is unavailable. Enable audio or try another browser.');
        return
    }
    speechSynthesis.cancel();
    let u=new SpeechSynthesisUtterance(questions[at].word);
    u.lang='en-US';
    u.rate=Number($('speechRate').value)||.85;
    u.voice=speechSynthesis.getVoices().find(v=>v.lang==='en-US')||speechSynthesis.getVoices().find(v=>v.lang.startsWith('en'))||null;
    u.onstart=()=>{
        $('toast').textContent='';
        $('listen').innerHTML=bi('↻ 再听一次','Play again');
        heard=true;
        document.querySelectorAll('.card').forEach(b=>b.disabled=locked)
    };
    u.onerror=()=>{
        $('toast').innerHTML=bi('发音未成功，请再试一次。','Audio failed. Please try again.')
    };
    speechSynthesis.speak(u)
}
